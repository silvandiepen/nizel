// Writes engine/src/unicode.rs from this JavaScript engine's own Unicode
// data, so the Rust engine agrees with V8 character for character.
//   node scripts/gen-engine-unicode.mjs
import { writeFile } from 'node:fs/promises';

/** BMP ranges where `test` holds for the single code unit. */
const ranges = (test) => {
  const out = [];
  let start = -1;
  for (let code = 0; code <= 0x10000; code += 1) {
    const inside = code < 0x10000 && !(code >= 0xd800 && code <= 0xdfff) && test(String.fromCharCode(code));
    if (inside && start === -1) start = code;
    if (!inside && start !== -1) { out.push([start, code - 1]); start = -1; }
  }
  return out;
};
const table = (name, list) =>
  `pub const ${name}: &[(u16, u16)] = &[\n${list.map(([a, b]) => `    (0x${a.toString(16)}, 0x${b.toString(16)}),`).join('\n')}\n];\n`;

const punctuation = ranges((c) => /[\p{P}\p{S}]/u.test(c));
const source = `//! Generated by scripts/gen-engine-unicode.mjs from Node ${process.version} (V8 ${process.versions.v8},
//! Unicode ${process.versions.unicode}). Do not edit by hand.

/// BMP code units matching \`/[\\p{P}\\p{S}]/u\`. Astral characters are never
/// tested whole: the JavaScript looks at single UTF-16 units, and a lone
/// surrogate matches neither class.
${table('PUNCTUATION', punctuation)}
pub fn in_table(table: &[(u16, u16)], c: char) -> bool {
    let Ok(unit) = u16::try_from(c as u32) else { return false };
    table.binary_search_by(|&(start, end)| {
        if end < unit { core::cmp::Ordering::Less } else if start > unit { core::cmp::Ordering::Greater } else { core::cmp::Ordering::Equal }
    }).is_ok()
}
`;
await writeFile(new URL('../engine/src/unicode.rs', import.meta.url), source);
console.log(`punctuation: ${punctuation.length} ranges`);
